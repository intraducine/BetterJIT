ROOT = Path(__file__).resolve().parents[1]


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


prepare = load('generalized_prepare', ROOT / 'addon/iridium/prepare.py')
config = prepare.configuration
sync_module = load('generalized_sync', ROOT / 'addon/iridium/sync.py')
exporter = load('generalized_export', ROOT / 'scripts/export-source.py')


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args], stderr=subprocess.DEVNULL).decode().strip()


def write(root, name, data):
    p = root / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data.encode() if isinstance(data, str) else data)


def commit(root):
    git(root, 'add', '.')
    git(root, 'commit', '-qm', 'Synthetic test fixture')
    return git(root, 'rev-parse', 'HEAD')


def init(root):
    root.mkdir()
    git(root, 'init', '-q')
    git(root, 'config', 'user.name', 'Fixture')
    git(root, 'config', 'user.email', 'fixture@example.invalid')


def unpack(archive, destination):
    # Extract only regular, validated members generated by these tests.
    with tarfile.open(archive) as tar:
        for member in tar.getmembers():
            config.safe_relative(member.name)
            if not member.isfile(): raise ValueError('Non-file fixture archive member')
            with tar.extractfile(member) as stream: write(destination, member.name, stream.read())


class ConfigurationTests(unittest.TestCase):
    def test_defaults_are_backwards_compatible(self):
        self.assertEqual(config.app_config()['appBundleIdentifier'], 'software.iridium.betterjit-local')

    def test_custom_app_and_helper_match(self):
        c = config.app_config({'appBundleIdentifier': 'net.example.mylab', 'appDisplayName': 'My Lab'})
        targets = prepare.project_spec('host', 'addon', c)['targets']
        self.assertEqual(targets['Iridium']['settings']['base']['PRODUCT_BUNDLE_IDENTIFIER'], 'net.example.mylab')
        self.assertEqual(targets['IridiumJITHelper']['settings']['base']['PRODUCT_BUNDLE_IDENTIFIER'], 'net.example.mylab.jit-helper')
        self.assertEqual(targets['Iridium']['info']['properties']['CFBundleDisplayName'], 'My Lab')
        self.assertNotIn('CODE_SIGN_ENTITLEMENTS', targets['Iridium']['settings']['base'])

    def test_invalid_config_is_rejected(self):
        for c in [[], {'schema': True}, {'schema': 2}, {'DEVELOPMENT_TEAM': 'not-a-team'},
                  {'appBundleIdentifier': 'software.iridium'}, {'appBundleIdentifier': 'abc'},
                  {'appBundleIdentifier': 'org.example.lab.jit-helper'}, {'appBundleIdentifier': 'org.$(whoami).lab'},
                  {'appBundleIdentifier': '../other'}, {'appBundleIdentifier': 'org.' + 'a' * 201 + '.lab'},
                  {'appDisplayName': ''}, {'appDisplayName': 'bad\nname'}, {'appDisplayName': '$(HOME)'},
                  {'appDisplayName': ' trailing '}, {'appDisplayName': 'x' * 41}]:
            with self.subTest(value=c), self.assertRaises(ValueError): config.app_config(c)

    def test_cli_overrides_file_but_does_not_hide_typos(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / 'config.json'
            p.write_text(json.dumps({'appBundleIdentifier': 'net.example.lab', 'appDisplayName': 'First'}))
            self.assertEqual(config.load_config(p, display_name='Second')['appDisplayName'], 'Second')
            p.write_text('{"typo": 1}')
            with self.assertRaises(ValueError): config.load_config(p, display_name='Second')

    def test_profile_registry_retains_pins(self):
        self.assertEqual(prepare.HOST_REFERENCE, 'f89099fa8810261fdffd334b2d4cd87e98b92ad1')
        self.assertEqual(len(prepare.HOST_PROFILES), 2)
        self.assertTrue(all(set(p['blobs']) == set(prepare.INTEGRATION_PATHS) for p in prepare.HOST_PROFILES))

    def test_invalid_registry_is_rejected(self):
        original = json.loads((ROOT / 'addon/iridium/host-profiles.json').read_text())
        with tempfile.TemporaryDirectory() as d:
            file = Path(d) / 'profiles.json'
            for alter in [lambda x: x.update(default='missing'), lambda x: x.update(schema=True),
                          lambda x: x['profiles'].append(x['profiles'][0]),
                          lambda x: x['profiles'][0]['blobs'].pop(prepare.INTEGRATION_PATHS[0]),
                          lambda x: x['profiles'][0].update(reference='main')]:
                data = json.loads(json.dumps(original)); alter(data); file.write_text(json.dumps(data))
                with self.assertRaises(ValueError): config.load_profiles(file, prepare.INTEGRATION_PATHS)

    def test_safe_relative_paths(self):
        for name in ['../outside', '/outside', 'a//b', './file', 'a/../b', 'a\\b', 'C:/x', 'a\nb']:
            with self.assertRaises(ValueError): config.safe_relative(name)
        self.assertEqual(config.safe_relative('addon/iridium/prepare.py'), 'addon/iridium/prepare.py')


