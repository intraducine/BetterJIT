    const out = {};
    for (const [k, v] of Object.entries(MODS)) {
      try { out[k] = WebAssembly.validate(new Uint8Array(v)); } catch (e) { out[k] = 'err:' + e; }
    }
    out.jspi = typeof WebAssembly.Suspending === 'function' && typeof WebAssembly.promising === 'function';
    out.js_string_builtins = (() => { try { return WebAssembly.validate(new Uint8Array(H), { builtins: ['js-string'] }); } catch (e) { return false; } })();
