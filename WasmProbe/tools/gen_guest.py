#!/usr/bin/env python3
"""Generates a synthetic "translated guest program" used by the dispatch test.

The program is a set of basic blocks operating on 16 64-bit guest registers
(kept in a memory-resident CPU state, as FEX does) and a 1 MB guest data
region. Each block ends with a data-dependent conditional or 4-way indirect
branch. The same program is emitted as:

  Web/guestprog.json   consumed by wasmgen.js, which JIT-generates wasm
  Sources/guestprog.c  native arm64 reference versions of the dispatch styles

All variants must produce the same checksum.
"""
import json, os, random, sys

N_BLOCKS = int(sys.argv[1]) if len(sys.argv) > 1 else 512
root = os.path.join(os.path.dirname(__file__), "..")
rng = random.Random(20260924)

OPS = ["add", "xor", "mul", "rot", "ld", "st"]
WEIGHTS = [5, 4, 1, 2, 3, 2]

blocks = []
for b in range(N_BLOCKS):
    ops = []
    for _ in range(rng.randint(6, 12)):
        op = rng.choices(OPS, WEIGHTS)[0]
        d, s = rng.randrange(16), rng.randrange(16)
        if op in ("add", "xor"):
            imm = rng.randrange(1, 1 << 31)
        elif op == "rot":
            imm = rng.randrange(1, 64)
        elif op in ("ld", "st"):
            imm = rng.randrange(0, 1 << 16) & ~7
        else:
            imm = 0
        ops.append([op, d, s, imm])
    if rng.random() < 0.7:
        term = {"kind": "cond", "c": rng.randrange(16), "t": [rng.randrange(N_BLOCKS) for _ in range(2)]}
    else:
        term = {"kind": "ind", "c": rng.randrange(16), "t": [rng.randrange(N_BLOCKS) for _ in range(4)]}
    blocks.append({"ops": ops, "term": term})

with open(os.path.join(root, "Web", "guestprog.json"), "w") as f:
    json.dump({"n": N_BLOCKS, "blocks": blocks}, f, separators=(",", ":"))


def uses(blk):
    used, written = set(), set()
    for op, d, s, _ in blk["ops"]:
        used |= {d, s}
        if op != "st":
            written.add(d)
    used.add(blk["term"]["c"])
    return sorted(used), sorted(written)


def body(blk, R, idx):
    out = []
    for op, d, s, imm in blk["ops"]:
        rd, rs = R(d), R(s)
        if op == "add":
            out.append(f"{rd} = {rd} + {rs} + {imm}ull;")
        elif op == "xor":
            out.append(f"{rd} = {rd} ^ ({rs} + {imm}ull);")
        elif op == "mul":
            out.append(f"{rd} = {rd} * ({rs} | 1);")
        elif op == "rot":
            out.append(f"{rd} = (({rd} << {imm}) | ({rd} >> {64 - imm})) ^ {rs};")
        elif op == "ld":
            out.append(f"{rd} = {rd} + GMEM(({rs} + {imm}ull) & 0xFFFF8);")
        elif op == "st":
            out.append(f"GMEM(({rs} + {imm}ull) & 0xFFFF8) = {rd};")
    t = blk["term"]
    c = R(t["c"])
    if t["kind"] == "cond":
        nxt = f"(({c} & 1) ? {t['t'][0]}u : {t['t'][1]}u)"
    else:
        nxt = f"gp_ind{idx}[{c} & 3]"
    return out, nxt


L = []
L.append("// Generated by tools/gen_guest.py — do not edit.")
L.append("#include <stdint.h>")
L.append("#include <string.h>")
L.append("#include \"guestprog.h\"")
L.append("uint8_t gp_gmem[1 << 20] __attribute__((aligned(64)));")
L.append("#define GMEM(off) (*(uint64_t *)(gp_gmem + (off)))")
for i, blk in enumerate(blocks):
    if blk["term"]["kind"] == "ind":
        L.append(f"static const uint32_t gp_ind{i}[4] = {{{', '.join(str(x) + 'u' for x in blk['term']['t'])}}};")

# Variant 1: one function per block, dispatcher loop through a pointer table.
L.append("typedef uint32_t (*gp_blk_fn)(uint64_t *R);")
for i, blk in enumerate(blocks):
    u, w = uses(blk)
    L.append(f"__attribute__((noinline)) static uint32_t gp_b{i}(uint64_t *R) {{")
    L.append("  " + " ".join(f"uint64_t r{x} = R[{x}];" for x in u))
    ops, nxt = body(blk, lambda x: f"r{x}", i)
    L += ["  " + o for o in ops]
    L.append("  uint32_t next = " + nxt + ";")
    L.append("  " + " ".join(f"R[{x}] = r{x};" for x in w))
    L.append("  return next;")
    L.append("}")
L.append(f"static const gp_blk_fn gp_table[{N_BLOCKS}] = {{" + ", ".join(f"gp_b{i}" for i in range(N_BLOCKS)) + "};")
L.append("void gp_run_fnptr(uint64_t *R, uint32_t steps) {")
L.append("  uint32_t pc = 0;")
L.append("  while (steps--) pc = gp_table[pc](R);")
L.append("}")

# Variant 2: one big function, registers in locals, switch dispatch.
L.append("void gp_run_switch(uint64_t *R, uint32_t steps) {")
L.append("  " + " ".join(f"uint64_t r{x} = R[{x}];" for x in range(16)))
L.append("  uint32_t pc = 0;")
L.append("  while (steps--) {")
L.append("    switch (pc) {")
for i, blk in enumerate(blocks):
    ops, nxt = body(blk, lambda x: f"r{x}", i)
    L.append(f"    case {i}: {{ " + " ".join(ops) + f" pc = {nxt}; break; }}")
L.append("    }")
L.append("  }")
L.append("  " + " ".join(f"R[{x}] = r{x};" for x in range(16)))
L.append("}")

# Variant 3: tail-call chaining (each block jumps straight to the next).
L.append("typedef void (*gp_tail_fn)(uint64_t *R, uint32_t steps);")
L.append(f"static const gp_tail_fn gp_ttable[{N_BLOCKS}];")
for i, blk in enumerate(blocks):
    u, w = uses(blk)
    L.append(f"static void gp_t{i}(uint64_t *R, uint32_t steps) {{")
    L.append("  " + " ".join(f"uint64_t r{x} = R[{x}];" for x in u))
    ops, nxt = body(blk, lambda x: f"r{x}", i)
    L += ["  " + o for o in ops]
    L.append("  uint32_t next = " + nxt + ";")
    L.append("  " + " ".join(f"R[{x}] = r{x};" for x in w))
    L.append("  if (--steps == 0) return;")
    L.append("  [[clang::musttail]] return gp_ttable[next](R, steps);")
    L.append("}")
L.append(f"static const gp_tail_fn gp_ttable[{N_BLOCKS}] = {{" + ", ".join(f"gp_t{i}" for i in range(N_BLOCKS)) + "};")
L.append("void gp_run_tail(uint64_t *R, uint32_t steps) { if (steps) gp_ttable[0](R, steps); }")

L.append("""
void gp_reset(uint64_t *R) {
  for (int i = 0; i < 16; i++) R[i] = (uint64_t)i * 0x1234567ull + 1;
  uint64_t *m = (uint64_t *)gp_gmem;
  for (int i = 0; i < (1 << 17); i++) m[i] = (uint64_t)i * 0x9E3779B97F4A7C15ull;
}

uint32_t gp_checksum(const uint64_t *R) {
  uint64_t h = 0;
  for (int i = 0; i < 16; i++) h = (h ^ R[i]) * 0x100000001B3ull;
  const uint64_t *m = (const uint64_t *)gp_gmem;
  for (int i = 0; i < (1 << 17); i++) h = (h ^ m[i]) * 0x100000001B3ull;
  return (uint32_t)(h ^ (h >> 32));
}
""")

with open(os.path.join(root, "Sources", "guestprog.c"), "w") as f:
    f.write("\n".join(L) + "\n")
with open(os.path.join(root, "Sources", "guestprog.h"), "w") as f:
    f.write("""#pragma once
#include <stdint.h>
void gp_reset(uint64_t *R);
uint32_t gp_checksum(const uint64_t *R);
void gp_run_fnptr(uint64_t *R, uint32_t steps);
void gp_run_switch(uint64_t *R, uint32_t steps);
void gp_run_tail(uint64_t *R, uint32_t steps);
""")
print(f"generated {N_BLOCKS} blocks")
