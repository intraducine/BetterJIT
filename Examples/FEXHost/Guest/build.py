#!/usr/bin/env python3
"""Reproduce the bundled x86 images. Requires Clang/LLD, not FEX or Xcode.

Normal app builds use GuestImage.swift and do not run this script. No recorded
Wasm/native ARM64 is included. Reject allocatable data and unresolved relocation
sections so the copied .text is a self-contained guest image at 0x400000.
"""
import argparse, base64, hashlib, json, os, pathlib, struct, subprocess, tempfile
ROOT = pathlib.Path(__file__).resolve().parent
FLAGS = ['--target=x86_64-unknown-linux-gnu','-O2','-ffreestanding','-fno-builtin',
         '-fno-stack-protector','-fno-pic','-mno-red-zone','-mno-sse','-mno-sse2',
         '-fno-vectorize','-fno-slp-vectorize','-fno-unwind-tables',
         '-fno-asynchronous-unwind-tables','-fno-jump-tables']
NAMES = ['add64','weighted16','branch_mix','nested_calls','mutate']
def elf(data):
    assert data[:6] == b'\x7fELF\x02\x01' and struct.unpack_from('<H', data,18)[0] == 62
    offset=struct.unpack_from('<Q',data,40)[0]; size,num,strings=struct.unpack_from('<HHH',data,58)
    sections=[struct.unpack_from('<IIQQQQIIQQ',data,offset+i*size) for i in range(num)]
    def body(s): return data[s[4]:s[4]+s[5]]
    def name(table,n): return table[n:table.index(0,n)].decode()
    names=body(sections[strings]); text=None; entries={}
    for s in sections:
        label=name(names,s[0]); content=body(s)
        if s[2]&2 and s[5]:
            assert label == '.text', ('unexpected allocated section',label)
            assert s[3] == 0x400000
            text=content
        assert not (s[1] in (4,9) and s[5]), 'unresolved relocations'
        if s[1]==2:
            table=body(sections[s[6]])
            for i in range(0,len(content),s[9]):
                n,info,other,index,value,length=struct.unpack_from('<IBBHQQ',content,i)
                key=name(table,n)
                if key in NAMES: entries[key]=value
    assert text and set(entries)==set(NAMES)
    assert all(0x400000 <= v < 0x400000+len(text) for v in entries.values())
    return text,entries

def generate(clang,linker):
    result={}
    with tempfile.TemporaryDirectory(prefix='betterjit-guest-') as t:
        root=pathlib.Path(t)
        for abi in ('sysv','win64'):
            obj=root/(abi+'.o'); executable=root/(abi+'.elf')
            subprocess.run([clang,*FLAGS,*(['-DWIN64'] if abi=='win64' else []),'-c',str(ROOT/'kernels.c'),'-o',str(obj)],check=True)
            subprocess.run([linker,'-Ttext=0x400000','--entry=add64','--build-id=none',str(obj),'-o',str(executable)],check=True)
            text,entries=elf(executable.read_bytes())
            result[abi]={'image':base64.b64encode(text).decode(),'sha256':hashlib.sha256(text).hexdigest(),'entries':entries}
    return result

def swift(images,compiler):
    lines=['// SPDX-License-Identifier: GPL-3.0-or-later','// Generated by Guest/build.py. Rebuild from kernels.c; do not edit bytes.',
           'import Foundation','enum CompiledGuest {',
           '    static let sourceSHA256 = '+json.dumps(hashlib.sha256((ROOT/'kernels.c').read_bytes()).hexdigest()),
           '    static let compiler = '+json.dumps(compiler),
           '    static let flags = '+json.dumps(' '.join(FLAGS)),
           '    static func image(_ abi: GuestABI) -> Data {',
           '        Data(base64Encoded: abi == .sysv ? sysv : win64)!','    }']
    for abi,v in images.items():
        lines+=['    static let '+abi+' = '+json.dumps(v['image']),
                '    static let '+abi+'SHA256 = '+json.dumps(v['sha256']),
                '    static let '+abi+'Entries: [String: UInt32] = ['+', '.join(json.dumps(k)+': '+hex(x) for k,x in sorted(v['entries'].items()))+']']
    lines+=['    static func entry(_ name: String, _ abi: GuestABI) -> UInt32 {',
            '        (abi == .sysv ? sysvEntries : win64Entries)[name]!','    }','}']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    clang=os.environ.get('CLANG','clang');linker=os.environ.get('LD_LLD','ld.lld')
    result=generate(clang,linker)
    compiler=subprocess.check_output([clang,'--version'],text=True).splitlines()[0]
    output=swift(result,compiler);destination=ROOT.parent/'GuestImage.swift'
    if a.check:
        assert destination.read_text()==output, 'Compiler or generated guest differs; review before replacing the fixture.'
    else: destination.write_text(output)
    print('Guest images:',', '.join(k+'='+str(len(base64.b64decode(v['image'])))+' bytes' for k,v in result.items()))
