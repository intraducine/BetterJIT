#!/usr/bin/env python3
"""Generate the bundled libc-free ELF; no external root or downloaded fixture."""
import base64, hashlib, pathlib, subprocess, tempfile
root = pathlib.Path(__file__).resolve().parent
source = root / 'linux-session.S'
with tempfile.TemporaryDirectory() as tmp:
    obj, elf = pathlib.Path(tmp)/'session.o', pathlib.Path(tmp)/'session.elf'
    subprocess.run(['as', '--64', '-o', str(obj), str(source)], check=True)
    subprocess.run(['ld', '-m', 'elf_x86_64', '--build-id=none', '-z', 'noexecstack', '-o', str(elf), str(obj)], check=True)
    raw = elf.read_bytes()
    text = '''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by Guest/build-linux.py from our libc-free assembly workload.
import Foundation

enum LinuxSessionFixture {
    static let sourceSHA256 = "%s"
    static let elfSHA256 = "%s"
    static let input = Data("BetterJIT data\\n".utf8)
    static let marker = "BetterJIT Linux services OK"
    static let elf = Data(base64Encoded: "%s")!
}
''' % (hashlib.sha256(source.read_bytes()).hexdigest(), hashlib.sha256(raw).hexdigest(), base64.b64encode(raw).decode())
    (root.parent/'LinuxSessionFixture.swift').write_text(text)
