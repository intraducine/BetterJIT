#!/usr/bin/env python3
"""Build reviewed SSE2 fixtures; normal device builds use ExtendedGuest.swift.

No FEX or Xcode invocation. Link only text and read-only constants into the
copied image; reject every other allocated section or unresolved relocation.
"""
import argparse, base64, hashlib, json, os, pathlib, struct, subprocess, tempfile
ROOT = pathlib.Path(__file__).resolve().parent
FLAGS = ['--target=x86_64-unknown-linux-gnu','-O2','-ffreestanding','-fno-builtin',
         '-fno-stack-protector','-fno-pic','-mno-red-zone','-msse2','-mno-sse3',
         '-mno-ssse3','-mno-sse4.1','-mno-sse4.2','-mno-avx','-fno-vectorize',
         '-fno-slp-vectorize','-fno-unroll-loops','-ffp-contract=off',
         '-fno-unwind-tables','-fno-asynchronous-unwind-tables','-fno-jump-tables']
NAMES = ['vector_words','vector_saturation','vector_f32','vector_f64','vector_lcg']
LINK = 'SECTIONS { . = 0x400000; .text : { *(.text .text.*) *(.rodata .rodata.*) } /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) } }'

def extract(data):
    if data[:6] != b'\x7fELF\x02\x01' or struct.unpack_from('<H',data,18)[0] != 62:
        raise ValueError('Expected little-endian ELF64 x86-64')
    offset=struct.unpack_from('<Q',data,40)[0]; size,num,strings=struct.unpack_from('<HHH',data,58)
    sections=[struct.unpack_from('<IIQQQQIIQQ',data,offset+i*size) for i in range(num)]
    def body(s): return data[s[4]:s[4]+s[5]]
    def name(table,n): return table[n:table.index(0,n)].decode()
    names=body(sections[strings]); image=None; entries={}
    for s in sections:
        label=name(names,s[0]); content=body(s)
        if s[2]&2 and s[5]:
            if label != '.text' or s[3] != 0x400000 or s[1] != 1: raise ValueError('Unexpected allocated section: '+label)
            image=content
        if s[1] in (4,9) and s[5]: raise ValueError('Unresolved relocation section')
        if s[1]==2:
            table=body(sections[s[6]])
            for i in range(0,len(content),s[9]):
                n,info,other,index,value,length=struct.unpack_from('<IBBHQQ',content,i)
                key=name(table,n)
                if key in NAMES: entries[key]=value
    if not image or set(entries)!=set(NAMES) or not all(0x400000<=v<0x400000+len(image) for v in entries.values()):
        raise ValueError('Missing or invalid fixture entry')
    return image,entries

def generate(clang,linker,dump=None):
    result={}
    with tempfile.TemporaryDirectory(prefix='betterjit-sse2-') as t:
        root=pathlib.Path(t); (root/'image.ld').write_text(LINK)
        for abi in ('sysv','win64'):
            obj=root/(abi+'.o'); exe=root/(abi+'.elf')
            subprocess.run([clang,*FLAGS,*(['-DWIN64'] if abi=='win64' else []),'-c',str(ROOT/'extended.c'),'-o',str(obj)],check=True)
            subprocess.run([linker,'-T',str(root/'image.ld'),'--entry=vector_words','--build-id=none',str(obj),'-o',str(exe)],check=True)
            image,entries=extract(exe.read_bytes())
            result[abi]={'image':base64.b64encode(image).decode(),'sha256':hashlib.sha256(image).hexdigest(),'entries':entries}
            if dump:
                dump.mkdir(parents=True,exist_ok=True); (dump/(abi+'.elf')).write_bytes(exe.read_bytes())
    return result

def swift(images,compiler):
    lines=['// SPDX-License-Identifier: GPL-3.0-or-later','// Generated by Guest/build-extended.py; no recorded Wasm.',
           'import Foundation','enum ExtendedGuest {',
           '    static let sourceSHA256 = '+json.dumps(hashlib.sha256((ROOT/'extended.c').read_bytes()).hexdigest()),
           '    static let compiler = '+json.dumps(compiler),'    static let flags = '+json.dumps(' '.join(FLAGS)),
           '    static func image(_ abi: GuestABI) -> Data { Data(base64Encoded: abi == .sysv ? sysv : win64)! }']
    for abi,v in images.items():
        lines += ['    static let '+abi+' = '+json.dumps(v['image']),
                  '    static let '+abi+'SHA256 = '+json.dumps(v['sha256']),
                  '    static let '+abi+'Entries: [String: UInt32] = ['+', '.join(json.dumps(k)+': '+hex(x) for k,x in sorted(v['entries'].items()))+']']
    lines+=['    static func entry(_ name: String, _ abi: GuestABI) -> UInt32 { (abi == .sysv ? sysvEntries : win64Entries)[name]! }','}']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--dump',type=pathlib.Path);a=p.parse_args()
    clang=os.environ.get('CLANG','clang');linker=os.environ.get('LD_LLD','ld.lld')
    result=generate(clang,linker,a.dump)
    output=swift(result,subprocess.check_output([clang,'--version'],text=True).splitlines()[0])
    destination=ROOT.parent/'ExtendedGuest.swift'
    if a.check:
        if destination.read_text()!=output: raise SystemExit('Compiler/fixture changed; review rather than silently replacing bytes.')
    else: destination.write_text(output)
    print('SSE2 guest bytes:',{k:len(base64.b64decode(v['image'])) for k,v in result.items()})
