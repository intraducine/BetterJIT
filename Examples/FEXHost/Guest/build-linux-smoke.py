#!/usr/bin/env python3
"""Build or verify the bundled Linux smoke fixture with Clang and LLD."""
import argparse
import base64
import os
from pathlib import Path
import subprocess
import tempfile
import textwrap

guest = Path(__file__).resolve().parent
destination = guest.parent / "LinuxSmokeFixture.swift"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()

with tempfile.TemporaryDirectory(prefix="betterjit-linux-smoke-") as directory:
    obj = Path(directory) / "smoke.o"
    elf = Path(directory) / "smoke.elf"
    subprocess.run([os.environ.get("CLANG", "clang"), "--target=x86_64-unknown-linux-gnu",
                    "-c", guest / "linux-smoke.S", "-o", obj], check=True)
    subprocess.run([os.environ.get("LD_LLD", "ld.lld"), "--strip-all", "--build-id=none",
                    "--no-rosegment", "--image-base=0x400000", "--entry=_start",
                    "-o", elf, obj], check=True)
    encoded = base64.b64encode(elf.read_bytes()).decode("ascii")

lines = "\n".join("        " + line for line in textwrap.wrap(encoded, 80))
swift = f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by Guest/build-linux-smoke.py from Guest/linux-smoke.S.
import Foundation

enum LinuxSmokeFixture {{
    static let elf = Data(base64Encoded: """
{lines}
        """.replacingOccurrences(of: "\\n", with: ""))!
}}
'''
if args.check:
    if destination.read_text() != swift:
        raise SystemExit("Bundled Linux smoke ELF differs from the assembled source.")
else:
    destination.write_text(swift)
