#!/usr/bin/env python3
"""Generate literal legacy vector-movement hardware oracle from compact cases."""
from pathlib import Path
import argparse
import json
ROOT=Path(__file__).resolve().parents[1]
def generate():
 s=json.loads((ROOT/'tests/sdk/linux-host/sparse-vector-moves-cases.json').read_text());cases=[]
 for f in s['forms']:
  for width in ([4,8] if not f['width'] else [f['width']]):
   code=([f['prefix']] if f['prefix'] else [])+([0x48] if not f['width'] and width==8 else [])+[0x0f,f['opcode'],(0xc8 if f['reverse'] else 0xc1) if f['kind']!=1 else 0xc0]
   cases.append((f,width,code))
 lines=['''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/generate-sparse-vector-moves-tests.py; x86 supplies results.
#include <inttypes.h>
#include <stdint.h>
#include <stdio.h>
#define EXEC(bytes) __asm__ volatile("movdqu %[old], %%xmm0; movdqu %[src], %%xmm1; pushfq; pop %[original]; push %[seed]; popfq; " bytes "; pushfq; pop %[flags]; push %[original]; popfq; movdqu %%xmm0, %[dst]; movdqu %%xmm1, %[kept]" : [original] "=&r"(original), [flags] "=&r"(flags), "+a"(value), [dst] "=m"(dst), [kept] "=m"(kept) : [seed] "r"(seed), [old] "m"(old), [src] "m"(src) : "xmm0","xmm1","cc","memory")
int main(void){
 const uint64_t patterns[][5]={'''+','.join('{'+','.join('UINT64_C('+n+')' for n in p)+'}' for p in s['patterns'])+'''};
 const unsigned seeds[]={'''+','.join(str(n) for n in s['flagSeeds'])+'''};uint64_t current;__asm__ volatile("pushfq; pop %0":"=r"(current)::"memory");int comma=0;puts("[");
 for(unsigned form=0;form<@FORMS@;form++)for(unsigned p=0;p<@PATTERNS@;p++)for(unsigned si=0;si<@SEEDS@;si++){
  const uint64_t src[]={patterns[p][0],patterns[p][1]},old[]={patterns[p][2],patterns[p][3]},seed=(current&~UINT64_C(0xcd5))|seeds[si];uint64_t value=patterns[p][4],dst[2],kept[2],original,flags;
  switch(form){''']
 for i,(f,w,c) in enumerate(cases):lines.append('case '+str(i)+':EXEC(".byte '+','.join(hex(b) for b in c)+'");break;')
 lines.append('''default:return 2;}
  printf("%s[%u,%u,%u,\\"0x%" PRIx64 "\\",\\"0x%" PRIx64 "\\",\\"0x%" PRIx64 "\\",\\"0x%" PRIx64 "\\",\\"0x%" PRIx64 "\\",%u]",comma?",\\n":"",form,p,si,value,dst[0],dst[1],kept[0],kept[1],(unsigned)flags&0xcd5);comma=1;
 }puts("\\n]");return 0;
}
''')
 return '\n'.join(lines).replace('@FORMS@',str(len(cases))).replace('@PATTERNS@',str(len(s['patterns']))).replace('@SEEDS@',str(len(s['flagSeeds'])))
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();dest=ROOT/'tests/sdk/linux-host/sparse-vector-moves-oracle.c';text=generate()
 if args.check:
  if dest.read_text()!=text:raise SystemExit('Generated vector oracle source differs')
  print('Literal vector oracle source matches compact cases')
 else:dest.write_text(text)
if __name__=='__main__':main()
